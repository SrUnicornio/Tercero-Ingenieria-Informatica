import express from 'express';
import path from 'path';
import os from 'os';
import { fileURLToPath } from 'url';

import livereload from 'livereload';
import connectLivereload from 'connect-livereload';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();

const PORT = 8080;
const HOST = '0.0.0.0';

/**
 * Root directory of the repository.
 */
const ROOT = path.join(__dirname, '..');

/**
 * Source directory containing the different projects.
 */
const SRC = path.join(ROOT, 'src');

/**
 * Documentation directory generated by TypeDoc.
 */
const DOCS = path.join(ROOT, 'docs');


/**
 * Detects the current IPv4 address of the machine.
 *
 * This function iterates through the available network interfaces
 * and returns the first non-internal IPv4 address found.
 *
 * This allows the server to automatically print the correct
 * network URL even if the machine receives a dynamic IP address.
 *
 * @return {string} Detected IPv4 address or 'localhost' if none found.
 */
function getLocalIP() {
  const interfaces = os.networkInterfaces();

  for (const name of Object.keys(interfaces)) {
    for (const net of interfaces[name]) {
      if (net.family === 'IPv4' && !net.internal) {
        return net.address;
      }
    }
  }
  return 'localhost';
}


/**
 * ---------------------------------------------------------
 * LiveReload configuration
 * ---------------------------------------------------------
 *
 * LiveReload automatically refreshes the browser when files
 * change in the watched directories.
 */
const liveReloadServer = livereload.createServer();

liveReloadServer.watch([
  path.join(__dirname),
  path.join(__dirname, '../src/home-work/shapes'),
  path.join(__dirname, '../src/evaluation-session/restangles'),
  path.join(__dirname, '../docs'),
]);

app.use(connectLivereload());


/**
 * ---------------------------------------------------------
 * Static directories
 * ---------------------------------------------------------
 *
 * These middleware serve static files directly from disk.
*/
// web-server
app.use(express.static(__dirname));
// src
app.use('/src', express.static(SRC));

/* homework practice */
app.use(express.static(
    path.join(SRC, 'home-work', 'shapes'),
));

/* evaluation practice */
app.use(express.static(
    path.join(SRC, 'evaluation-session', 'restangles'),
));

/* documentation */
app.use('/docs', express.static(DOCS));

/**
 * ---------------------------------------------------------
 * Main index route
 * ---------------------------------------------------------
 *
 * Serves the main index page of the server.
 */

app.get('/', (req, res) => {
  res.sendFile(
      path.join(__dirname, 'server.html'),
  );
});


/**
 * ---------------------------------------------------------
 * Server startup
 * ---------------------------------------------------------
 */

app.listen(PORT, HOST, () => {
  const ip = getLocalIP();

  console.log('\nServidor iniciado correctamente\n');

  console.log('Acceso local:');
  console.log(`http://localhost:${PORT}`);

  console.log('\nAcceso desde red:');
  console.log(`http://${ip}:${PORT}\n`);
});


/**
 * ---------------------------------------------------------
 * LiveReload connection trigger
 * ---------------------------------------------------------
 */

liveReloadServer.server.once('connection', () => {
  setTimeout(() => {
    liveReloadServer.refresh('/');
  }, 100);
});
